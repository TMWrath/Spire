import test from 'node:test';
import assert from 'node:assert/strict';
import {createLocalRuntime} from './local/runtime.mjs';
for(const action of ['keep-server','keep-device','keep-both','merge'])test(`manual Local resolves ${action} at the reviewed revision`,async()=>{
 let disk={files:{'Writing/file.md':Buffer.from('base').toString('base64')},dirs:['Writing']};
 const bridge={manual:true,load:async()=>structuredClone(disk),commit:async(before,after)=>{disk=structuredClone(after);}};
 let runtime=await createLocalRuntime(bridge,'conflict-actions');
 const post=(url,body)=>runtime.fetch(url,{method:'POST',body:JSON.stringify(body)});
 const snap=async()=> (await runtime.fetch('/api/snapshot')).json();
 const original=(await snap()).notes[0];
 const mutation=(n,content)=>({op:crypto.randomUUID(),id:n.id,base:n.rev,path:n.path,content,deleted:false});
 let r=await post('/api/mutate',mutation(original,'current'));assert.equal(r.status,200,await r.clone().text());
 r=await post('/api/mutate',mutation(original,'device'));assert.equal(r.status,409,await r.clone().text());
 let s=await snap();assert.equal(s.conflicts.length,1);
 const c=s.conflicts[0];
 r=await post('/api/conflicts/'+c.id+'/resolve',{action,expectedServerRevision:c.current,path:'Writing/copy.md',content:'merged'});
 assert.equal(r.status,200,await r.clone().text());
 assert.equal((await snap()).conflicts.length,0);
 const expected=action==='keep-device'?'device':action==='merge'?'merged':'current';
 assert.equal(Buffer.from(disk.files['Writing/file.md'],'base64').toString(),expected);
 if(action==='keep-both')assert.equal(Buffer.from(disk.files['Writing/copy.md'],'base64').toString(),'device');
 runtime=await createLocalRuntime(bridge,'conflict-actions');assert.equal((await snap()).conflicts.length,0);
});
