import test from 'node:test';
import assert from 'node:assert/strict';
import {createLocalRuntime} from './local/runtime.mjs';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const durableNote=(disk,id)=>{
 const state=JSON.parse(Buffer.from(disk.files['.spire-android/state.json'],'base64').toString()),metadata=state.notes[id];
 if(typeof metadata.content==='string')return metadata;
 const path=metadata.bucketPath??`.spire-android/notes-${metadata.bucket.toString(16).padStart(2,'0')}.json`;
 return JSON.parse(Buffer.from(disk.files[path],'base64').toString()).notes[id];
};
test('automatic sync waits thirty seconds and pauses while hidden',async()=>{
 const sourceRoot=process.env.SPIRE_SOURCE??path.resolve(import.meta.dirname,'..');
 const source=fs.readFileSync(path.join(sourceRoot,'client/sync.ts'),'utf8');
 const block=source.match(/async function refreshConnectedWorkspaces\(\)\{[\s\S]*?\n\}\nsetInterval\([^\n]+/)?.[0];
 assert.ok(block,'connected-workspace refresh timer must remain present');
 let callback,delay,calls=0;
 const document={visibilityState:'hidden'},mounted={busy:false,engines:[{manualLocal:false,sync:async()=>{calls++;}}],refreshSharing:async()=>{},remote:null};
 vm.runInNewContext(block,{setInterval:(fn,ms)=>{callback=fn;delay=ms;},document,mounted,Promise,Error});
 assert.equal(delay,30000);callback();await new Promise(resolve=>setImmediate(resolve));assert.equal(calls,0);
 document.visibilityState='visible';callback();await new Promise(resolve=>setImmediate(resolve));assert.equal(calls,1);
});
test('directory edits become active content with cached history preserved',async()=>{
 let disk={files:{'Good/file.md':Buffer.from('good').toString('base64'),'Changed/file.md':Buffer.from('cached version').toString('base64')},dirs:['Good','Changed']};
 const bridge={load:async()=>structuredClone(disk),commit:async(b,a)=>{assert.deepEqual(b,disk);disk=structuredClone(a);}};
 await createLocalRuntime(bridge,'changed');
 const original=JSON.parse(Buffer.from(disk.files['.spire-android/state.json'],'base64').toString());
 const oldMetadata=Object.values(original.notes).find(n=>n.path==='Changed/file.md'),old=durableNote(disk,oldMetadata.id);
 disk.files['Changed/file.md']=Buffer.from('external version').toString('base64');
 const runtime=await createLocalRuntime(bridge,'changed');
 const snapshot=await(await runtime.fetch('/api/snapshot')).json();
 assert.equal(snapshot.notes.length,2);
 assert.equal(snapshot.notes.find(n=>n.path==='Changed/file.md').content,'external version');
 assert.equal(runtime.warnings.length,0);
 assert.equal((await runtime.fetch('/api/export')).status,200);
 assert.equal((await runtime.fetch('/api/transfers?path=Changed')).status,200);
 const n=snapshot.notes[0];
 assert.equal((await runtime.fetch('/api/mutate',{method:'POST',body:JSON.stringify({...n,base:n.rev,op:crypto.randomUUID(),content:'edited'})})).status,200);
 assert.equal(disk.files['Changed/file.md'],Buffer.from('external version').toString('base64'));
 const updated=durableNote(disk,old.id);assert.equal(updated.content,'external version');assert.ok(updated.history.some(h=>h.content===old.content));
 assert.equal((await runtime.fetch('/api/mutate',{method:'POST',body:JSON.stringify({...old,base:old.rev,op:crypto.randomUUID(),content:'overwrite'})})).status,409);
});
