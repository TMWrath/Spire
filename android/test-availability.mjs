test('all read-only startup routes reuse the index and cannot create a save journal',async()=>{
 let disk={files:{'Good/file.md':Buffer.from('good').toString('base64')},dirs:['Good']},commits=0;
 const storage={load:async()=>structuredClone(disk),commit:async(b,a)=>{commits++;disk=structuredClone(a);}};
 await createLocalRuntime(storage,'reads');
 disk.files=Object.fromEntries(Object.entries(disk.files).reverse());disk.dirs.reverse();delete disk.warnings;
 const runtime=await createLocalRuntime(storage,'reads'),baseline=commits,before=structuredClone(disk);
 for(const path of ['/api/me','/api/devices','/api/reliquary','/api/health','/api/search?q=good'])assert.equal((await runtime.fetch(path)).status,200);
 assert.equal(runtime.diagnostics.indexBuilds,1);assert.equal(commits,baseline);assert.deepEqual(disk,before);
 assert.equal((await runtime.fetch('/api/logout',{method:'POST'})).status,200);assert.equal(commits,baseline,'a semantic no-op cannot commit because object order or warning fields differ');
});
