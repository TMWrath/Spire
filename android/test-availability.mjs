test('missing indexed file/folder is skipped without blocking healthy edits or destroying recoverable metadata',async()=>{
 let disk={files:{'Good/file.md':Buffer.from('good').toString('base64'),'Gone/file.md':Buffer.from('recover me').toString('base64')},dirs:['Good','Gone']};
 const bridge={load:async()=>structuredClone(disk),commit:async(b,a)=>{assert.deepEqual(b,disk);disk=structuredClone(a);}};
 await createLocalRuntime(bridge,'availability');
 const original=JSON.parse(Buffer.from(disk.files['.spire-android/state.json'],'base64').toString());
 const originalMissingMetadata=Object.values(original.notes).find(n=>n.path==='Gone/file.md'),originalMissing=durableNote(disk,originalMissingMetadata.id);
 delete disk.files['Gone/file.md'];disk.dirs=disk.dirs.filter(p=>p!=='Gone');
 const runtime=await createLocalRuntime(bridge,'availability');
 const snapshot=await(await runtime.fetch('/api/snapshot')).json();
 assert.equal(snapshot.notes.length,1);assert.equal(snapshot.notes[0].path,'Good/file.md');
 assert.equal(runtime.warnings.length,0);
 assert.ok(!snapshot.folders.includes('Gone'));
 assert.equal((await runtime.fetch('/api/transfers?path=Gone')).status,404);
 assert.equal((await runtime.fetch('/api/export')).status,200,'export the actual directory, not cached missing files');
 const n=snapshot.notes[0];const r=await runtime.fetch('/api/mutate',{method:'POST',body:JSON.stringify({...n,base:n.rev,op:crypto.randomUUID(),content:'edited'})});
 assert.equal(r.status,200,await r.clone().text());
 assert.equal(Buffer.from(disk.files['Good/file.md'],'base64').toString(),'edited');
 assert.equal(disk.files['Gone/file.md'],undefined,'do not recreate missing bytes');
 assert.ok(!disk.dirs.includes('Gone'),'do not recreate missing folder');
 const saved=JSON.parse(Buffer.from(disk.files['.spire-android/state.json'],'base64').toString()),savedMissing=durableNote(disk,originalMissingMetadata.id);
 const {bucket:savedBucket,bucketPath:savedPath,...savedContent}=savedMissing,{bucket:originalBucket,bucketPath:originalPath,...originalContent}=originalMissing;
 assert.deepEqual(savedContent,originalContent,'preserve full history and content');
 const {bucketPath:oldPath,...oldMetadata}=originalMissingMetadata,{bucketPath:newPath,...newMetadata}=saved.notes[originalMissingMetadata.id];
 assert.deepEqual(newMetadata,oldMetadata,'preserve unavailable note identity and revision while its shared bucket advances');
 const blocked=await runtime.fetch('/api/folders',{method:'POST',body:JSON.stringify({path:'Gone'})});assert.equal(blocked.status,201);
 disk.files['Gone/file.md']=Buffer.from('recover me').toString('base64');disk.dirs.push('Gone');
 const reopened=await createLocalRuntime(bridge,'availability');assert.equal((await(await reopened.fetch('/api/snapshot')).json()).notes.length,2);
});
