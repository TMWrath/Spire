import {test,expect} from './fixtures';
import {selectDropdown} from './dropdown';
for(const mobile of [false,true])test.describe(mobile?'mobile':'desktop',()=>{
 test.use({hasTouch:mobile,viewport:mobile?{width:390,height:844}:{width:1280,height:900},timezoneId:'America/Los_Angeles'});
 test('Journal lifecycle, same-day entries, isolation and persistent Diary naming',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Username',{exact:true}).fill('journal-writer');
  await page.getByLabel('Password',{exact:true}).fill('journal-test-password');
  await page.getByRole('button',{name:'Create Reliquary',exact:true}).click();
  await page.getByRole('region',{name:'Journal',exact:true}).getByRole('button',{name:'New journal entry',exact:true}).click();
  const path=page.getByLabel('File path',{exact:true});
  await expect(path).toHaveValue(/^Journal\//);
  const first=await path.inputValue();
  await page.getByRole('button',{name:'Source',exact:true}).click();
  const source=page.getByLabel('Markdown source',{exact:true});
  await expect(source).toHaveValue(/## Today[\s\S]*## On my mind[\s\S]*## Looking ahead/);
  const original=await source.inputValue();
  await source.fill(original+'A quiet evening.\n');
  await page.getByRole('button',{name:'Save file',exact:true}).click();
  await page.getByRole('toolbar',{name:'File actions'}).getByRole('button',{name:'New journal entry',exact:true}).click();
  await expect(path).not.toHaveValue(first);
  const second=await path.inputValue();
  expect(second.slice(8,18)).toBe(first.slice(8,18));
  await page.getByRole('button',{name:'Home',exact:true}).click();
  if(mobile)await page.getByRole('button',{name:'Toggle folders',exact:true}).click();
  await page.getByRole('tab',{name:'Journal',exact:true}).click();
  const list=page.locator('#sidebar-journal');
  await expect(list.locator('.library-file')).toHaveCount(2);
  await list.getByTitle(first,{exact:true}).click();
  await page.getByRole('button',{name:'Source',exact:true}).click();
  await expect(source).toHaveValue(original+'A quiet evening.\n');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('tab',{name:'Personalization',exact:true}).click();
  await page.getByRole('tab',{name:'Writing',exact:true}).click();
  await selectDropdown(page.getByLabel('Personal writing name',{exact:true}),'Diary');
  await page.reload();
  if(mobile)await page.getByRole('button',{name:'Toggle folders',exact:true}).click();
  await expect(page.getByRole('tab',{name:'Diary',exact:true})).toBeVisible();
  await expect(page.getByRole('tab',{name:'Journal',exact:true})).toHaveCount(0);
  await page.getByRole('tab',{name:'Files',exact:true}).click();
  await expect(page.locator('#sidebar-files')).not.toContainText('Journal');
  await page.getByRole('tab',{name:'Projects',exact:true}).click();
  await expect(page.locator('#sidebar-projects')).not.toContainText('Journal');
  await page.getByRole('tab',{name:'Diary',exact:true}).click();
  await expect(list.locator('.library-file')).toHaveCount(2);
  await list.getByRole('button',{name:'New diary entry',exact:true}).click();
  await expect(path).toHaveValue(/^Journal\//);
  await expect(page.getByRole('toolbar',{name:'File actions'}).getByRole('button',{name:'New diary entry',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('region',{name:'Diary',exact:true}).getByRole('button',{name:'New diary entry',exact:true}).click();
  await expect(path).toHaveValue(/^Journal\//);
  const snapshot=await (await page.request.get('/api/snapshot')).json();
  expect(snapshot.notes).toHaveLength(4);
  expect(new Set(snapshot.notes.map((n:{path:string})=>n.path)).size).toBe(4);
 });
});
